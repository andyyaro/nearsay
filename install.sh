#!/bin/bash
# nearsay installer for macOS.
# Safe to re-run: it upgrades the code in place and keeps your config, keys and history.
#
#   ./install.sh              install or upgrade
#   ./install.sh --uninstall  remove the agent and phone key (keeps ~/.nearsay)
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TAP_HOME="${NEARSAY_HOME:-$HOME/.nearsay}"

if [ -t 1 ]; then G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; B=$'\033[1m'; N=$'\033[0m'; else G=; Y=; R=; B=; N=; fi
ok()   { printf '%s\n' "${G}✓${N} $*"; }
warn() { printf '%s\n' "${Y}⚠${N} $*"; }
die()  { printf '%s\n' "${R}✗${N} $*" >&2; exit 1; }

if [ "${1:-}" = "--uninstall" ]; then
  exec "$TAP_HOME/bin/nearsay" uninstall "${@:2}"
fi

[ "$(uname -s)" = "Darwin" ] || [ "${NEARSAY_ALLOW_NON_MACOS:-}" = "1" ] || die "nearsay runs on macOS."

case "$TAP_HOME" in
  *[[:space:]]* | *\"* | *\'* | *\\*) die "The install folder ($TAP_HOME) must not contain spaces, quotes or backslashes." ;;
esac

# ---------------------------------------------------------------- Python 3.9+
find_python() {
  local c
  for c in "${NEARSAY_PYTHON:-}" /usr/bin/python3 /opt/homebrew/bin/python3 /usr/local/bin/python3 "$(command -v python3 2>/dev/null || true)"; do
    [ -n "$c" ] && [ -x "$c" ] || continue
    # /usr/bin/python3 is only a stub that pops up an installer until the Command Line Tools exist.
    if [ "$c" = "/usr/bin/python3" ] && [ "$(uname -s)" = "Darwin" ] && ! xcode-select -p >/dev/null 2>&1; then
      continue
    fi
    if "$c" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)' >/dev/null 2>&1; then
      printf '%s' "$c"
      return 0
    fi
  done
  return 1
}
PY="$(find_python)" || die "Python 3.9+ not found. Install Apple's Command Line Tools (xcode-select --install) or Homebrew Python, then re-run."
ok "Python: $PY ($("$PY" -c 'import platform; print(platform.python_version())'))"

# ---------------------------------------------------------------- Claude Code
CLAUDE="${NEARSAY_CLAUDE:-}"
if [ -z "$CLAUDE" ]; then
  for c in "$(command -v claude 2>/dev/null || true)" "$HOME/.local/bin/claude" /opt/homebrew/bin/claude /usr/local/bin/claude; do
    if [ -n "$c" ] && [ -x "$c" ]; then CLAUDE="$c"; break; fi
  done
fi
if [ -n "$CLAUDE" ]; then
  ok "Claude Code: $CLAUDE"
else
  warn "Claude Code not found. Install it (https://code.claude.com/docs/en/setup), then run: nearsay set claude_path \"\$(command -v claude)\""
fi

# ---------------------------------------------------------------- copy code
mkdir -p "$TAP_HOME"
chmod 700 "$TAP_HOME"
for d in app bin queue incoming jobs logs; do mkdir -p "$TAP_HOME/$d"; chmod 700 "$TAP_HOME/$d"; done
rm -rf "$TAP_HOME/app.new" "$TAP_HOME/app.old"
mkdir -p "$TAP_HOME/app.new"
cp -R "$SRC_DIR/nearsay" "$TAP_HOME/app.new/nearsay"
cp "$SRC_DIR/nearsay_entry.py" "$TAP_HOME/app.new/"
find "$TAP_HOME/app.new" -name '__pycache__' -type d -prune -exec rm -rf {} +
mv "$TAP_HOME/app" "$TAP_HOME/app.old"
mv "$TAP_HOME/app.new" "$TAP_HOME/app"
rm -rf "$TAP_HOME/app.old"
ok "Installed code in $TAP_HOME/app"

write_wrapper() {  # name, subcommand-or-empty
  local f="$TAP_HOME/bin/$1"
  {
    printf '#!/bin/sh\n'
    printf '# Generated by nearsay install.sh\n'
    printf "NEARSAY_HOME='%s'\n" "$TAP_HOME"
    printf 'export NEARSAY_HOME\n'
    if [ -n "$2" ]; then
      printf "exec '%s' -I '%s/app/nearsay_entry.py' %s\n" "$PY" "$TAP_HOME" "$2"
    else
      printf "exec '%s' -I '%s/app/nearsay_entry.py' \"\$@\"\n" "$PY" "$TAP_HOME"
    fi
  } > "$f.tmp"
  chmod 755 "$f.tmp"
  mv "$f.tmp" "$f"
}
write_wrapper nearsay ""
write_wrapper nearsay-receive receive
write_wrapper nearsay-dispatch dispatch
ok "Wrote commands in $TAP_HOME/bin"

TAP="$TAP_HOME/bin/nearsay"
export NEARSAY_HOME="$TAP_HOME"

# ---------------------------------------------------------------- config + agent
if [ -f "$TAP_HOME/config.json" ]; then
  ok "Kept existing config $TAP_HOME/config.json"
else
  if [ -n "$CLAUDE" ]; then "$TAP" init --claude-path "$CLAUDE"; else "$TAP" init; fi
fi
"$TAP" install-agent

# ---------------------------------------------------------------- put nearsay on PATH
mkdir -p "$HOME/.local/bin"
ln -sfn "$TAP" "$HOME/.local/bin/nearsay"
case ":$PATH:" in
  *":$HOME/.local/bin:"*) ok "nearsay is on your PATH" ;;
  *) warn "Add ~/.local/bin to your PATH to type 'nearsay' directly:  echo 'export PATH=\"\$HOME/.local/bin:\$PATH\"' >> ~/.zprofile" ;;
esac

echo
printf '%s\n' "${B}Checkup${N}"
"$TAP" doctor || true

cat <<EOF

${B}Next steps${N}
  1. Mac: System Settings → General → Sharing → Remote Login → on
     ("Allow access for: Only these users" → just you; leave "full disk access for remote users" OFF).
  2. Add your projects, e.g.:
       nearsay project add orkestra ~/code/orkestra --alias orchestra --default
  3. iPhone: build the Shortcut and NFC automation (docs/IPHONE.md). Values to type in:
       nearsay phone
  4. Copy the Shortcut's public key, AirDrop or Universal-Clipboard it to this Mac, then:
       nearsay add-key --from-clipboard
  5. Try the Mac side alone:  nearsay test "In inbox, say hello"
     Then tap the sticker for real.
EOF
